//! The ratchet baseline (`tests/opencypher/baseline.toml`): every in-scope test case that does
//! not pass, with its class and a one-line reason, plus the gate that compares a run against it.
//!
//! Copied from the TinkerPop harness's `baseline.rs` and adapted (W42: copy, never share): own
//! classes, own environment variable, reasons normalized by [`reason_of`].
//!
//! # File format
//!
//! A deliberately tiny TOML subset, read and written by hand (no dependency): `#` comment lines,
//! blank lines, and one table per case, sorted by id:
//!
//! ```toml
//! ["clauses/match/Match1.feature::[1] Match non-existent nodes returns empty"]
//! class = "missing"
//! reason = "not yet: MERGE"
//! ```
//!
//! Keys are TOML basic strings (`\\`, `\"`, `\n`, `\t`, `\r`, `\uXXXX` escapes). Anything else is a
//! parse error, so a hand edit that leaves the subset is caught instead of silently ignored.
//!
//! # Gate
//!
//! See [`gate`]: a non-passing case without an entry is a regression; an entry whose case passes,
//! no longer exists or is excluded from the scope (`scope.rs`) is stale; a case still failing
//! under another class than recorded is reported, never failed (except on the forwarding
//! storage, where the target fails on any class change).

use std::collections::BTreeMap;

use super::classify::{self, Class, Outcome};

/// Environment variable that makes the conformance test rewrite the baseline from the current run.
pub const UPDATE_ENV: &str = "OPENCYPHER_UPDATE_BASELINE";

/// Maximum length (in characters) of a recorded reason.
pub const REASON_MAX: usize = 160;

/// One baseline entry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Entry {
    /// The recorded class name ([`Class::name`]), e.g. `wrong_result`.
    pub class: String,
    /// One-line reason (stable across runs, at most [`REASON_MAX`] characters).
    pub reason: String,
}

/// The whole baseline, keyed and ordered by case id.
pub type Baseline = BTreeMap<String, Entry>;

/// Header written at the top of the baseline file.
const HEADER: &str = "\
# openCypher TCK ratchet baseline: every in-scope test case that does not pass, with its class.
# Generated by
#   OPENCYPHER_UPDATE_BASELINE=1 cargo test --package graphersal --features script,io,display,serde,persist,gql --test opencypher_tck
# Review diffs like code. Removing an entry means \"this case passes now\".
";

/// The reason recorded for an outcome, stable across message edits: for `missing` the refused
/// construct (`classify::construct`, e.g. `not yet: MERGE`), for `setup` the same after the
/// failing step (`having executed: not yet: duration()`), otherwise the detail without the
/// trailing `(step #..)` note; cut to [`REASON_MAX`] characters.
pub fn reason_of(outcome: &Outcome) -> String {
    let normalized = match outcome.class {
        Class::Missing => classify::construct(&outcome.detail),
        Class::Setup => format!(
            "{}{}",
            classify::context_prefix(&outcome.detail),
            classify::construct(&outcome.detail)
        ),
        _ => outcome
            .detail
            .split(" (step #")
            .next()
            .unwrap_or_default()
            .to_string(),
    };
    let detail = normalized.trim();
    if detail.chars().count() > REASON_MAX {
        let mut cut: String = detail.chars().take(REASON_MAX - 1).collect();
        cut.push('…');
        cut
    } else {
        detail.to_string()
    }
}

/// Builds the baseline of a run: one entry per non-passing, in-scope (not excluded) case.
pub fn from_outcomes<'a>(outcomes: impl IntoIterator<Item = (&'a str, &'a Outcome)>) -> Baseline {
    outcomes
        .into_iter()
        .filter(|(_, o)| !matches!(o.class, Class::Pass | Class::Excluded))
        .map(|(id, o)| {
            (
                id.to_string(),
                Entry {
                    class: o.class.name().to_string(),
                    reason: reason_of(o),
                },
            )
        })
        .collect()
}

fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", u32::from(c))),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Parses one basic string starting at `text` (which must begin with `"`); returns the value and
/// the rest after the closing quote.
fn unescape(text: &str) -> Result<(String, &str), String> {
    let body = text
        .strip_prefix('"')
        .ok_or_else(|| format!("expected a quoted string, got `{text}`"))?;
    let mut out = String::new();
    let mut chars = body.char_indices();
    while let Some((i, c)) = chars.next() {
        match c {
            '"' => return Ok((out, &body[i + 1..])),
            '\\' => match chars.next() {
                Some((_, '"')) => out.push('"'),
                Some((_, '\\')) => out.push('\\'),
                Some((_, 'n')) => out.push('\n'),
                Some((_, 't')) => out.push('\t'),
                Some((_, 'r')) => out.push('\r'),
                Some((j, 'u')) => {
                    let hex = body
                        .get(j + 1..j + 5)
                        .ok_or_else(|| "truncated \\u escape".to_string())?;
                    let code = u32::from_str_radix(hex, 16)
                        .map_err(|_| format!("bad \\u escape `{hex}`"))?;
                    out.push(
                        char::from_u32(code).ok_or_else(|| format!("bad code point {code:X}"))?,
                    );
                    for _ in 0..4 {
                        chars.next();
                    }
                }
                other => return Err(format!("unsupported escape {other:?}")),
            },
            c => out.push(c),
        }
    }
    Err("unterminated string".to_string())
}

/// Renders a baseline in the file format (deterministic: sorted by id, fixed key order).
pub fn render(baseline: &Baseline) -> String {
    let mut out = String::from(HEADER);
    for (id, entry) in baseline {
        out.push('\n');
        out.push_str(&format!("[{}]\n", escape(id)));
        out.push_str(&format!("class = {}\n", escape(&entry.class)));
        out.push_str(&format!("reason = {}\n", escape(&entry.reason)));
    }
    out
}

/// Parses a baseline file. Unknown class names, keys, duplicate ids and missing keys are errors.
pub fn parse(text: &str) -> Result<Baseline, String> {
    let mut baseline = Baseline::new();
    // (id, class, reason, line of the header)
    let mut current: Option<(String, Option<String>, Option<String>, usize)> = None;

    let finish = |baseline: &mut Baseline,
                  current: Option<(String, Option<String>, Option<String>, usize)>|
     -> Result<(), String> {
        let Some((id, class, reason, line)) = current else {
            return Ok(());
        };
        let class = class.ok_or_else(|| format!("line {line}: entry `{id}` has no `class`"))?;
        let reason = reason.unwrap_or_default();
        if baseline
            .insert(id.clone(), Entry { class, reason })
            .is_some()
        {
            return Err(format!("line {line}: duplicate entry `{id}`"));
        }
        Ok(())
    };

    for (index, raw) in text.lines().enumerate() {
        let line_no = index + 1;
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(inner) = line.strip_prefix('[') {
            let (id, rest) = unescape(inner).map_err(|e| format!("line {line_no}: {e}"))?;
            if rest.trim() != "]" {
                return Err(format!("line {line_no}: expected `]` after the table name"));
            }
            finish(&mut baseline, current.take())?;
            current = Some((id, None, None, line_no));
            continue;
        }
        let (key, value) = line
            .split_once('=')
            .ok_or_else(|| format!("line {line_no}: expected `key = \"value\"`"))?;
        let (value, rest) = unescape(value.trim()).map_err(|e| format!("line {line_no}: {e}"))?;
        if !rest.trim().is_empty() {
            return Err(format!("line {line_no}: trailing text after the value"));
        }
        let Some((_, class, reason, _)) = current.as_mut() else {
            return Err(format!("line {line_no}: key outside of an entry"));
        };
        match key.trim() {
            "class" => {
                if !Class::ALL
                    .iter()
                    .any(|c| !matches!(c, Class::Pass | Class::Excluded) && c.name() == value)
                {
                    return Err(format!("line {line_no}: unknown class `{value}`"));
                }
                *class = Some(value);
            }
            "reason" => *reason = Some(value),
            other => return Err(format!("line {line_no}: unknown key `{other}`")),
        }
    }
    finish(&mut baseline, current)?;
    Ok(baseline)
}

/// A case that fails without a baseline entry.
#[derive(Debug, Clone, PartialEq)]
pub struct Regression {
    /// Case id.
    pub id: String,
    /// Current class name.
    pub class: &'static str,
    /// Current one-line detail.
    pub detail: String,
}

/// A case still failing, but under another class than the baseline records.
#[derive(Debug, Clone, PartialEq)]
pub struct ClassChange {
    /// Case id.
    pub id: String,
    /// Class recorded in the baseline.
    pub recorded: String,
    /// Current class name.
    pub current: &'static str,
    /// Current one-line detail.
    pub detail: String,
}

/// Result of comparing one run against the baseline.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct GateResult {
    /// Non-passing cases without an entry (fail the gate).
    pub regressions: Vec<Regression>,
    /// Entries whose case passes now (fail the gate).
    pub now_passing: Vec<String>,
    /// Entries whose case id does not exist any more or is excluded from the compatibility
    /// scope (fail the gate).
    pub unknown: Vec<String>,
    /// Still failing under a different class (reported only).
    pub class_changed: Vec<ClassChange>,
}

impl GateResult {
    /// Whether the gate fails.
    pub fn failed(&self) -> bool {
        !self.regressions.is_empty() || !self.now_passing.is_empty() || !self.unknown.is_empty()
    }

    /// Human-readable failure message (empty when the gate passes).
    pub fn failure_message(&self) -> String {
        let mut out = String::new();
        if !self.regressions.is_empty() {
            out.push_str(&format!(
                "{} regression(s): cases not in the baseline that do not pass:\n",
                self.regressions.len()
            ));
            for r in &self.regressions {
                out.push_str(&format!("  {} [{}]: {}\n", r.id, r.class, r.detail));
            }
        }
        if !self.now_passing.is_empty() {
            out.push_str(&format!(
                "{} stale baseline entr(y/ies): these cases pass now:\n",
                self.now_passing.len()
            ));
            for id in &self.now_passing {
                out.push_str(&format!("  {id}\n"));
            }
        }
        if !self.unknown.is_empty() {
            out.push_str(&format!(
                "{} stale baseline entr(y/ies): no such case in scope (nonexistent or excluded):\n",
                self.unknown.len()
            ));
            for id in &self.unknown {
                out.push_str(&format!("  {id}\n"));
            }
        }
        if !self.now_passing.is_empty() || !self.unknown.is_empty() {
            out.push_str(&format!(
                "remove these entries from tests/opencypher/baseline.toml (or rerun with {UPDATE_ENV}=1)\n"
            ));
        }
        if !self.regressions.is_empty() {
            out.push_str(&format!(
                "fix the regressions; if a new failure is intended, record it with {UPDATE_ENV}=1 and review the diff\n"
            ));
        }
        out
    }
}

/// Compares a run (every case of the suite with its outcome) against the baseline.
pub fn gate<'a>(
    baseline: &Baseline,
    outcomes: impl IntoIterator<Item = (&'a str, &'a Outcome)>,
) -> GateResult {
    let mut result = GateResult::default();
    let mut seen = std::collections::BTreeSet::new();
    for (id, outcome) in outcomes {
        // An excluded case is out of scope: an entry for it is stale like an unknown id.
        if outcome.class == Class::Excluded {
            continue;
        }
        seen.insert(id);
        match (baseline.get(id), outcome.class) {
            (None, Class::Pass) => {}
            (Some(_), Class::Pass) => result.now_passing.push(id.to_string()),
            (None, class) => result.regressions.push(Regression {
                id: id.to_string(),
                class: class.name(),
                detail: outcome.detail.clone(),
            }),
            (Some(entry), class) if entry.class != class.name() => {
                result.class_changed.push(ClassChange {
                    id: id.to_string(),
                    recorded: entry.class.clone(),
                    current: class.name(),
                    detail: outcome.detail.clone(),
                })
            }
            (Some(_), _) => {}
        }
    }
    result.unknown = baseline
        .keys()
        .filter(|id| !seen.contains(id.as_str()))
        .cloned()
        .collect();
    result.regressions.sort_by(|a, b| a.id.cmp(&b.id));
    result.now_passing.sort();
    result.class_changed.sort_by(|a, b| a.id.cmp(&b.id));
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    fn outcome(class: Class, detail: &str) -> Outcome {
        Outcome {
            class,
            detail: detail.to_string(),
        }
    }

    #[test]
    fn render_parse_round_trip() {
        let a = outcome(Class::WrongResult, "expected [\"a\\b\"]\tgot []");
        let b = outcome(
            Class::Missing,
            "GQL construct not supported yet at line 1, column 1: SET is not yet supported",
        );
        let p = outcome(Class::Pass, "");
        let baseline =
            from_outcomes([("x/B.feature::b", &b), ("x/A.feature::a\"q", &a), ("p", &p)]);
        assert_eq!(baseline.len(), 2);
        let text = render(&baseline);
        assert!(text.starts_with("# openCypher TCK"));
        assert!(text.find("A.feature").unwrap_or(0) < text.find("B.feature").unwrap_or(0));
        assert_eq!(parse(&text), Ok(baseline.clone()));
        assert_eq!(render(&parse(&text).unwrap_or_default()), text);
    }

    #[test]
    fn excluded_cases_have_no_entries_and_stale_entries() {
        let excluded = outcome(Class::Excluded, "excluded:procedures");
        let failing = outcome(
            Class::Missing,
            "GQL construct not supported yet at line 1, column 1: SET is not yet supported",
        );
        assert_eq!(
            from_outcomes([("x", &excluded), ("y", &failing)])
                .keys()
                .collect::<Vec<_>>(),
            vec!["y"]
        );
        assert!(parse("[\"a\"]\nclass = \"excluded\"\n").is_err());
        let baseline = parse("[\"x\"]\nclass = \"missing\"\nreason = \"r\"\n").unwrap_or_default();
        let result = gate(&baseline, [("x", &excluded)]);
        assert_eq!(result.unknown, vec!["x".to_string()]);
        assert!(result.failed());
        assert!(!gate(&Baseline::new(), [("x", &excluded)]).failed());
    }

    #[test]
    fn reasons_are_truncated() {
        let long = "x".repeat(400);
        let r = reason_of(&outcome(Class::UnexpectedError, &long));
        assert_eq!(r.chars().count(), REASON_MAX);
        assert!(r.ends_with('…'));
    }

    #[test]
    fn reasons_are_normalized() {
        let missing = outcome(
            Class::Missing,
            "GQL construct not supported yet at line 3, column 1: SET is not yet supported in \
             this version (step #1 'gql:error(\"0A000\")' refused the query)",
        );
        assert_eq!(reason_of(&missing), "not yet: SET");
        let setup = outcome(
            Class::Setup,
            "having executed: GQL construct not supported yet at line 1, column 9: date() (a \
             date or time function) is not yet supported in this version",
        );
        assert_eq!(reason_of(&setup), "having executed: not yet: date()");
        let error = outcome(
            Class::UnexpectedError,
            "GQL syntax error at line 1, column 2: unexpected `:` (step #1 'gql:error(\"42001\")')",
        );
        assert_eq!(
            reason_of(&error),
            "GQL syntax error at line 1, column 2: unexpected `:`"
        );
    }

    #[test]
    fn parse_errors() {
        assert!(parse("[\"a\"]\nreason = \"r\"\n").is_err(), "missing class");
        assert!(
            parse("[\"a\"]\nclass = \"nope\"\n").is_err(),
            "unknown class"
        );
        assert!(
            parse("[\"a\"]\nclass = \"pass\"\n").is_err(),
            "pass is no entry"
        );
        assert!(parse("[\"a\"]\nclass = \"missing\"\nfoo = \"x\"\n").is_err());
        assert!(parse("class = \"missing\"\n").is_err(), "key outside entry");
        assert!(parse("[\"a\"]\nclass = \"missing\"\n[\"a\"]\nclass = \"missing\"\n").is_err());
        assert!(parse("[\"a]\n").is_err(), "unterminated");
        assert_eq!(parse("# only a comment\n\n").map(|b| b.len()), Ok(0));
    }

    #[test]
    fn gate_semantics() {
        let baseline = parse(
            "[\"still\"]\nclass = \"missing\"\nreason = \"x\"\n\
             [\"fixed\"]\nclass = \"unexpected_error\"\nreason = \"x\"\n\
             [\"shifted\"]\nclass = \"missing\"\nreason = \"x\"\n\
             [\"gone\"]\nclass = \"missing\"\nreason = \"x\"\n",
        )
        .unwrap_or_default();
        let still = outcome(
            Class::Missing,
            "GQL construct not supported yet at line 1, column 1: SET is not yet supported",
        );
        let fixed = outcome(Class::Pass, "");
        let shifted = outcome(Class::WrongResult, "diff");
        let new = outcome(Class::UnexpectedError, "boom");
        let ok = outcome(Class::Pass, "");
        let run = [
            ("still", &still),
            ("fixed", &fixed),
            ("shifted", &shifted),
            ("new", &new),
            ("ok", &ok),
        ];
        let result = gate(&baseline, run);
        assert!(result.failed());
        assert_eq!(result.regressions.len(), 1);
        assert_eq!(result.regressions[0].id, "new");
        assert_eq!(result.now_passing, vec!["fixed".to_string()]);
        assert_eq!(result.unknown, vec!["gone".to_string()]);
        assert_eq!(result.class_changed.len(), 1);
        assert_eq!(result.class_changed[0].recorded, "missing");
        assert_eq!(result.class_changed[0].current, "wrong_result");
        let message = result.failure_message();
        assert!(
            message.contains("new [unexpected_error]: boom"),
            "{message}"
        );
        assert!(message.contains(UPDATE_ENV), "{message}");

        // A class change alone never fails the gate.
        let clean = gate(
            &baseline,
            [
                ("still", &shifted),
                ("fixed", &new),
                ("shifted", &still),
                ("gone", &still),
            ],
        );
        assert!(!clean.failed(), "{clean:?}");
        assert_eq!(clean.class_changed.len(), 1);
        assert_eq!(clean.class_changed[0].id, "still");
    }
}
