//! The step reference of the book is generated from the engine's function catalogue
//! (`views::completion_entries`: every DSL function, both spellings, its overloads, its
//! one-sentence text and its example with the result; the same data as `/help`, the
//! playground's completion and MCP's `graphersal://dsl-reference`):
//!
//! - one page per step, `book/src/traversal/steps/<name>.md`, unless a hand-written page of that
//!   name exists (a page without the [`MARK`] line is hand-written and left alone);
//! - one page per group of the other functions, `book/src/traversal/functions/*.md`;
//! - the index by category on `traversal/step_reference.md` and the alphabetical list of the
//!   pages in `SUMMARY.md`, each between `<!-- steps:begin -->` and `<!-- steps:end -->`.
//!
//! The test fails when a file differs from what the catalogue renders, when a generated file is
//! left over for a function that no longer exists, or when a step has no category in
//! [`CATEGORIES`]; `GRAPHERSAL_UPDATE_BOOK=1` writes everything (and removes leftovers). An
//! example that runs in the playground's session is fenced ```` ```rhai,graph=modern ```` (a run
//! link, and `book_playground_examples` runs it); one that reads or writes files is not.

