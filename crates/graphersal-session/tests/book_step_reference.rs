/// The relative link from the page `from` to `to`, both below `book/src/`.
fn rel(from: &str, to: &str) -> String {
    let depth = from.matches('/').count();
    format!("{}{to}", "../".repeat(depth))
}

/// One entry's text: the sentence, the example and what it gives.
struct Doc {
    summary: String,
    example: Option<String>,
    outcome: Outcome,
}

enum Outcome {
    None,
    Returns(String),
    Fails(String),
}

fn parse_doc(doc: &str) -> Doc {
    let (summary, example) = doc.split_once("\n\nExample: ").unwrap_or((doc, ""));
    let summary = summary.trim().replace('\n', " ");
    if example.is_empty() {
        return Doc {
            summary,
            example: None,
            outcome: Outcome::None,
        };
    }
    let strip = |s: &str| s.trim().trim_matches('`').to_string();
    let (example, outcome) = if let Some((ex, res)) = example.rsplit_once("` returns `") {
        (strip(ex), Outcome::Returns(strip(res)))
    } else if let Some((ex, err)) = example.rsplit_once("` fails with `") {
        (strip(ex), Outcome::Fails(strip(err)))
    } else {
        (strip(example), Outcome::None)
    };
    Doc {
        summary,
        example: Some(example),
        outcome,
    }
}

fn cut(text: &str, max: usize) -> String {
    let text = text.replace('\n', " ");
    if text.chars().count() <= max {
        return text;
    }
    let mut s: String = text.chars().take(max).collect();
    s.push('…');
    s
}

/// Whether the example runs in the playground's session as documented (an example that fails
/// on purpose must fail; one that needs a file does not run there and gets no run link).
fn runs_in_playground(example: &str, outcome: &Outcome) -> bool {
    let mut session = Session::new();
    session.load_sample("modern").expect("modern");
    let r: Value =
        serde_json::from_str(&session.execute(example, &RunOptions::default())).expect("JSON");
    (r["ok"] == true) != matches!(outcome, Outcome::Fails(_))
}

/// The example as a code block with its result as a comment.
fn example_block(out: &mut String, doc: &Doc) {
    let Some(example) = &doc.example else { return };
    let comment = match &doc.outcome {
        Outcome::Returns(r) => format!("   // {}", cut(r, 100)),
        Outcome::Fails(r) => format!("   // error: {}", cut(r, 100)),
        Outcome::None => String::new(),
    };
    let fence = if runs_in_playground(example, &doc.outcome) {
        "```rhai,graph=modern"
    } else {
        "```rhai"
    };
    let _ = writeln!(out, "{fence}\n{example}{comment}\n```\n");
}

fn spellings(e: &CompletionEntry, prefix: &str) -> String {
    std::iter::once(&e.name)
        .chain(e.aliases.iter())
        .map(|n| format!("`{prefix}{n}`"))
        .collect::<Vec<_>>()
        .join(" · ")
}

fn step_path(name: &str) -> String {
    format!("traversal/steps/{name}.md")
}

/// The page of one step.
fn step_page(e: &CompletionEntry, category: &str) -> String {
    let path = step_path(&e.name);
    let doc = parse_doc(&e.doc);
    let mut out = format!("{MARK}\n# Step - {}\n\n", e.name);
    let _ = writeln!(
        out,
        "{} · category: [{category}]({}#{})\n",
        spellings(e, ""),
        rel(&path, "traversal/step_reference.md"),
        anchor(category)
    );
    let _ = writeln!(out, "{}\n", doc.summary);
    if !e.signatures.is_empty() {
        let _ = writeln!(out, "## Forms\n\n```text");
        for s in &e.signatures {
            let _ = writeln!(out, "{}{s}", e.name);
        }
        let _ = writeln!(out, "```\n");
    }
    if doc.example.is_some() {
        let _ = writeln!(out, "## Example\n");
        example_block(&mut out, &doc);
    }
    let mut more: Vec<(&str, &str)> = SEE_ALSO
        .iter()
        .filter(|(n, _, _)| *n == e.name)
        .map(|(_, t, p)| (*t, *p))
        .collect();
    if let Some(page) = category_page(category) {
        more.push(page);
    }
    more.dedup();
    if !more.is_empty() {
        let _ = writeln!(out, "## See also\n");
        for (title, to) in more {
            let _ = writeln!(out, "- [{title}]({})", rel(&path, to));
        }
        out.push('\n');
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// The page of a group of non-step functions.
fn group_page_text(
    file: &str,
    title: &str,
    receivers: &[&str],
    entries: &[CompletionEntry],
) -> String {
    let path = format!("traversal/functions/{file}");
    let mut out = format!("{MARK}\n# {title}\n\n");
    if let Some((t, to)) = group_page(file) {
        let _ = writeln!(out, "See also [{t}]({}).\n", rel(&path, to));
    }
    for receiver in receivers {
        for e in entries.iter().filter(|e| e.receiver == *receiver) {
            let prefix = if *receiver == "global" {
                String::new()
            } else {
                format!("{receiver}.")
            };
            let doc = parse_doc(&e.doc);
            // A free function with the text of a P/TextP function (`gt(30)` is `P.gt(30)`).
            if *receiver == "global"
                && let Some(twin) = entries
                    .iter()
                    .find(|t| matches!(t.receiver.as_str(), "P" | "TextP") && t.doc == e.doc)
            {
                let _ = writeln!(
                    out,
                    "**{}**: the same as `{}.{}`, without the class name.\n",
                    spellings(e, ""),
                    twin.receiver,
                    twin.name
                );
                continue;
            }
            let _ = writeln!(out, "**{}**: {}\n", spellings(e, &prefix), doc.summary);
            example_block(&mut out, &doc);
        }
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// The anchor mdBook gives a heading.
fn anchor(title: &str) -> String {
    title
        .to_lowercase()
        .chars()
        .filter_map(|c| match c {
            'a'..='z' | '0'..='9' | '-' | '_' => Some(c),
            ' ' => Some('-'),
            _ => None,
        })
        .collect()
}

/// The index of `step_reference.md`: every category with its steps.
fn index_block(traversal: &[&CompletionEntry]) -> String {
    let mut out = String::from("\n");
    for (title, names) in CATEGORIES {
        let _ = writeln!(out, "### {title}\n");
        let links: Vec<String> = names
            .iter()
            .filter(|n| traversal.iter().any(|e| e.name == **n))
            .map(|n| format!("[`{n}`](steps/{n}.md)"))
            .collect();
        let _ = writeln!(out, "{}\n", links.join(" · "));
    }
    let _ = writeln!(out, "### Predicates, tokens and test data\n");
    let links: Vec<String> = GROUPS
        .iter()
        .map(|(file, title, _)| format!("[{title}](functions/{file})"))
        .collect();
    let _ = writeln!(out, "{}\n", links.join(" · "));
    out
}

/// The "Step Reference" entry of `SUMMARY.md` with its pages nested below it: the group and topic
/// pages, then every step page in alphabetical order. The markers stand around the whole entry:
/// an HTML comment between a list item and its nested list would end the nesting in mdBook.
fn summary_block(traversal: &[&CompletionEntry]) -> String {
    let mut out = String::from("\n- [Step Reference](traversal/step_reference.md)\n");
    for (file, title, _) in GROUPS {
        let _ = writeln!(out, "  - [{title}](traversal/functions/{file})");
    }
    for (title, path) in TOPIC_PAGES {
        let _ = writeln!(out, "  - [{title}]({path})");
    }
    let mut names: Vec<&str> = traversal.iter().map(|e| e.name.as_str()).collect();
    names.sort_unstable();
    for name in names {
        let _ = writeln!(out, "  - [{name}]({})", step_path(name));
    }
    out
}

fn replace_block(text: &str, block: &str, what: &str) -> Result<String, String> {
    let (Some(start), Some(end)) = (text.find(BEGIN), text.find(END)) else {
        return Err(format!("{what} has no {BEGIN} ... {END} block"));
    };
    Ok(format!("{}{BEGIN}{block}{}", &text[..start], &text[end..]))
}

#[test]
fn the_step_reference_has_a_page_for_every_step() {
    let session = Session::new();
    let entries = completion_entries(session.engine());
    let traversal: Vec<&CompletionEntry> = entries
        .iter()
        .filter(|e| e.receiver == "traversal")
        .collect();

    let mut unclassified: Vec<&str> = traversal
        .iter()
        .filter(|e| !CATEGORIES.iter().any(|(_, n)| n.contains(&e.name.as_str())))
        .map(|e| e.name.as_str())
        .collect();
    unclassified.sort_unstable();
    let stale: Vec<&str> = CATEGORIES
        .iter()
        .flat_map(|(_, n)| n.iter().copied())
        .filter(|n| !traversal.iter().any(|e| e.name == *n))
        .collect();
    assert!(
        unclassified.is_empty() && stale.is_empty(),
        "CATEGORIES in this test is out of date: steps without a category: {unclassified:?}; \
         names that are no step: {stale:?}"
    );
    let receivers: Vec<&str> = GROUPS
        .iter()
        .flat_map(|(_, _, r)| r.iter().copied())
        .collect();
    let mut ungrouped: Vec<&str> = entries
        .iter()
        .map(|e| e.receiver.as_str())
        .filter(|r| *r != "traversal" && !receivers.contains(r))
        .collect();
    ungrouped.dedup();
    assert!(
        ungrouped.is_empty(),
        "GROUPS in this test misses the receivers {ungrouped:?}"
    );

    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../book/src");
    // Every file this test owns, with the text it must have.
    let mut files: BTreeMap<PathBuf, String> = BTreeMap::new();
    for e in &traversal {
        let path = src.join(step_path(&e.name));
        let hand_written = std::fs::read_to_string(&path).is_ok_and(|t| !t.starts_with(MARK));
        if hand_written {
            continue;
        }
        let category = CATEGORIES
            .iter()
            .find(|(_, n)| n.contains(&e.name.as_str()))
            .map(|(t, _)| *t)
            .unwrap_or_default();
        files.insert(path, step_page(e, category));
    }
    for (file, title, receivers) in GROUPS {
        files.insert(
            src.join("traversal/functions").join(file),
            group_page_text(file, title, receivers, &entries),
        );
    }
    let reference = src.join("traversal/step_reference.md");
    let summary = src.join("SUMMARY.md");
    let read = |p: &Path| std::fs::read_to_string(p).unwrap_or_default();
    files.insert(
        reference.clone(),
        replace_block(
            &read(&reference),
            &index_block(&traversal),
            "step_reference.md",
        )
        .unwrap_or_else(|e| panic!("{e}")),
    );
    files.insert(
        summary.clone(),
        replace_block(&read(&summary), &summary_block(&traversal), "SUMMARY.md")
            .unwrap_or_else(|e| panic!("{e}")),
    );

    // Generated pages left over for functions that no longer exist.
    let mut leftovers = Vec::new();
    for dir in ["traversal/steps", "traversal/functions"] {
        for entry in std::fs::read_dir(src.join(dir))
            .into_iter()
            .flatten()
            .flatten()
        {
            let path = entry.path();
            if !files.contains_key(&path) && read(&path).starts_with(MARK) {
                leftovers.push(path);
            }
        }
    }

    let update = std::env::var_os("GRAPHERSAL_UPDATE_BOOK").is_some();
    let mut differ = Vec::new();
    for (path, text) in &files {
        if read(path) != *text {
            if update {
                std::fs::create_dir_all(path.parent().expect("dir")).expect("create dir");
                std::fs::write(path, text).expect("write");
            } else {
                differ.push(
                    path.strip_prefix(&src)
                        .unwrap_or(path)
                        .display()
                        .to_string(),
                );
            }
        }
    }
    for path in &leftovers {
        if update {
            std::fs::remove_file(path).expect("remove leftover");
        }
    }
    if update {
        return;
    }
    let leftovers: Vec<String> = leftovers
        .iter()
        .map(|p| p.strip_prefix(&src).unwrap_or(p).display().to_string())
        .collect();
    assert!(
        differ.is_empty() && leftovers.is_empty(),
        "the step reference of the book is out of date with the engine's catalogue.\n\
         differ: {differ:?}\nleft over: {leftovers:?}\n\
         regenerate: GRAPHERSAL_UPDATE_BOOK=1 cargo test -p graphersal-session --test book_step_reference"
    );
}
